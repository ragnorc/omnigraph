#!/usr/bin/env python3
"""Summarise the instrument's runs into docs/spikes/gq3-instrument/results.md and results.json.

    python3 docs/spikes/gq3-instrument/summarize.py
"""
import collections
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RUNS = os.path.join(HERE, "runs")


def load():
    runs = {}
    for d in sorted(os.listdir(RUNS)):
        if not d.startswith("e"):
            continue
        ed, r = d[1], d.split("-r")[1]
        recs = [json.load(open(os.path.join(RUNS, d, f))) for f in sorted(os.listdir(os.path.join(RUNS, d)))]
        runs[(int(ed), int(r))] = {rec["task"]: rec for rec in recs}
    return runs


def code(rec, k="try1"):
    c = rec[k]["check"]
    return c.get("diagnostic", {}).get("code") if not c.get("parse_ok") else None


def main():
    runs = load()
    tasks = {}
    for f in sorted(os.listdir(os.path.join(HERE, "tasks"))):
        t = json.load(open(os.path.join(HERE, "tasks", f)))
        tasks[t["id"]] = t
    out = []
    w = out.append
    summary = {}
    w("# Instrument results\n")
    w("Generated by `summarize.py` from `runs/`. One row per edition and run.\n")
    w("| Edition | Run | Tasks | First-try valid | Valid after one repair | Repairs | Semantic equal / with truth | Tokens in | Tokens out | Models |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for (ed, r), recs in sorted(runs.items()):
        n = len(recs)
        first = sum(x["first_try_valid"] for x in recs.values())
        after = sum(x["valid_after_repair"] for x in recs.values())
        rep = sum(x["repaired"] for x in recs.values())
        withtruth = [x for x in recs.values() if x["has_truth"]]
        sem = sum(bool(x["final_semantic_equal"]) for x in withtruth)
        tin = sum(x["tokens_in"] for x in recs.values())
        tout = sum(x["tokens_out"] for x in recs.values())
        models = sorted({m for x in recs.values() for k in ("try1", "try2") if k in x for m in x[k]["models"]})
        summary[f"e{ed}r{r}"] = dict(tasks=n, first=first, after=after, repairs=rep, sem=sem,
                                     with_truth=len(withtruth), tokens_in=tin, tokens_out=tout, models=models)
        w(f"| {ed} | {r} | {n} | {first}/{n} | {after}/{n} | {rep} | {sem}/{len(withtruth)} | {tin} | {tout} | {', '.join(models)} |")
    w("")
    # adjudication
    adj = json.load(open(os.path.join(HERE, "adjudication.json")))
    def verdict(ed, tid, r, rec):
        if not rec["has_truth"]:
            return None
        if rec["final_semantic_equal"]:
            return "equal"
        v = adj.get(f"{ed}/{tid}/{r}") or adj.get(f"{ed}/{tid}/all")
        return v[0] if v else "unadjudicated"
    shared = [tid for tid, t in tasks.items() if t["truth2"]]
    w("## Semantic correctness, adjudicated\n")
    w("`equal` is tree (edition 3) or typed-IR (edition 2) equality with a ground truth after renaming; every other "
      "answer was read by hand (`adjudication.json`). Correct = equal + equivalent + renamed + extra. The last column "
      f"restricts edition 3 to the {len(shared)} tasks that have an edition-2 truth.\n")
    w("| Edition | Run | equal | equivalent | renamed | extra | alternative | wrong | correct / with truth | correct on the shared tasks |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for (ed, r), recs in sorted(runs.items()):
        cnt = collections.Counter(verdict(ed, tid, r, rec) for tid, rec in recs.items())
        cnt_shared = collections.Counter(verdict(ed, tid, r, rec) for tid, rec in recs.items() if tid in shared)
        ok = lambda c: c["equal"] + c["equivalent"] + c["renamed"] + c["extra"]
        withtruth = sum(1 for x in recs.values() if x["has_truth"])
        w(f"| {ed} | {r} | {cnt['equal']} | {cnt['equivalent']} | {cnt['renamed']} | {cnt['extra']} | {cnt['alternative']} | "
          f"{cnt['wrong'] + cnt['unadjudicated']} | {ok(cnt)}/{withtruth} | {ok(cnt_shared)}/{len(shared)} |")
        summary[f"e{ed}r{r}"]["adjudicated"] = dict(cnt)
    w("")
    # spread
    for ed in (2, 3):
        firsts = [summary[k]["first"] for k in summary if k.startswith(f"e{ed}")]
        afters = [summary[k]["after"] for k in summary if k.startswith(f"e{ed}")]
        sems = [summary[k]["sem"] for k in summary if k.startswith(f"e{ed}")]
        if firsts:
            w(f"- Edition {ed}: first-try valid {min(firsts)}–{max(firsts)} of 45 over {len(firsts)} runs; "
              f"after one repair {min(afters)}–{max(afters)}; semantic equal {min(sems)}–{max(sems)}.")
    w("")
    # per task
    w("## Per task\n")
    w("Cells: first-try parse (`ok` or the code), `→ok`/`→code` after the repair, then `=` when the final answer "
      "equals a ground truth, `≠` when it does not, `·` when the edition has no ground truth; `qN` is the number "
      "of declarations in the final answer when it is not one; `T65?` marks a ranking call in `order` or `return`, "
      "which the parser-only build accepts and the RFC's type checker refuses.\n")
    hdr = "| Task | Kind | " + " | ".join(f"e{ed} r{r}" for (ed, r) in sorted(runs)) + " |"
    w(hdr)
    w("|" + "---|" * (2 + len(runs)))
    per_kind = collections.defaultdict(lambda: collections.Counter())
    repair_codes = collections.Counter()
    for tid, t in tasks.items():
        cells = []
        for key in sorted(runs):
            rec = runs[key].get(tid)
            if rec is None:
                cells.append("–")
                continue
            ed = key[0]
            c = code(rec)
            s = "ok" if c is None else c
            if rec["repaired"]:
                repair_codes[(ed, c)] += 1
                c2 = code(rec, "try2")
                s += "→ok" if c2 is None else f"→{c2}"
            if rec["has_truth"]:
                s += " =" if rec["final_semantic_equal"] else " ≠"
            else:
                s += " ·"
            final = rec.get("try2", rec["try1"])["check"]
            if final.get("parse_ok") and final.get("decls", 1) != 1:
                s += f" q{final.get('decls')}"
            if final.get("t65_ranking_call_in_order_or_return"):
                s += " T65?"
            cells.append(s)
            per_kind[(tid, ed)]["first"] += rec["first_try_valid"]
            per_kind[(tid, ed)]["n"] += 1
        w(f"| {tid} | {t['kind']}{' (M0: ' + t['m0'] + ')' if t['m0'] else ''} | " + " | ".join(cells) + " |")
    w("")
    w("## Validity by task, edition 3 against edition 2 (first try, over the runs)\n")
    w("| Task | Kind | Edition 2 | Edition 3 | Change |")
    w("|---|---|---|---|---|")
    for tid, t in tasks.items():
        a, b = per_kind[(tid, 2)], per_kind[(tid, 3)]
        if a["n"] and b["n"] and a["first"] * b["n"] != b["first"] * a["n"]:
            ch = "gained" if b["first"] * a["n"] > a["first"] * b["n"] else "lost"
            w(f"| {tid} | {t['kind']} | {a['first']}/{a['n']} | {b['first']}/{b['n']} | {ch} |")
    w("")
    w("## Diagnostic codes that caused a repair\n")
    w("| Edition | Code | Repairs |")
    w("|---|---|---|")
    for (ed, c), n in sorted(repair_codes.items(), key=lambda x: (x[0][0], str(x[0][1]))):
        w(f"| {ed} | {c} | {n} |")
    w("")
    # composition
    w("## The six composition tasks\n")
    w("| Task | Composition | " + " | ".join(f"e{ed} r{r}" for (ed, r) in sorted(runs)) + " |")
    w("|" + "---|" * (2 + len(runs)))
    for tid, t in tasks.items():
        if not t["m0"]:
            continue
        cells = []
        for key in sorted(runs):
            rec = runs[key].get(tid)
            final = rec.get("try2", rec["try1"]) if rec else None
            if not final:
                cells.append("–")
                continue
            c = final["check"]
            cells.append(f"{final['blocks']} block(s), {c.get('decls', '?')} decl(s){'' if c.get('parse_ok') else ', refused'}")
        w(f"| {tid} | {t['m0']} | " + " | ".join(cells) + " |")
    w("")
    # seeded repairs
    sdir = os.path.join(HERE, "seeds")
    reps = sorted(d for d in os.listdir(sdir) if d.startswith("rep"))
    if reps:
        seeds = json.load(open(os.path.join(sdir, "seeds.json")))
        w("## Seeded repairs (edition 3)\n")
        w("Each seed is an edition-3 answer written with a habit the RFC refuses. `accepted` means the parser-only "
          "build took it, so no repair turn was sent. Otherwise: the code, and per repetition whether one repair "
          "turn produced a parsing answer (`ok`) and whether it equals a ground truth (`=`) or not (`≠`).\n")
        w("| Seed | Task | Habit | Parser | " + " | ".join(reps) + " |")
        w("|---|---|---|---|" + "---|" * len(reps))
        for sd in seeds:
            cells = []
            parser = None
            for rp in reps:
                f = os.path.join(sdir, rp, sd["id"] + ".json")
                if not os.path.exists(f):
                    cells.append("–")
                    continue
                rec = json.load(open(f))
                if not rec["refused"]:
                    parser = "accepted"
                    cells.append("·")
                    continue
                parser = rec["seed_check"]["diagnostic"]["code"]
                c = rec["repair"]["check"]
                cells.append(("ok" if c.get("parse_ok") else c.get("diagnostic", {}).get("code", "?"))
                             + (" =" if rec.get("semantic_equal") else " ≠"))
            w(f"| {sd['id']} | {sd['task']} | {sd['habit']} | {parser} | " + " | ".join(cells) + " |")
        w("")
    open(os.path.join(HERE, "results.md"), "w").write("\n".join(out) + "\n")
    json.dump(summary, open(os.path.join(HERE, "results.json"), "w"), indent=2)
    print("\n".join(out[:30]))


if __name__ == "__main__":
    main()
